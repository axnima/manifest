const assert=require('node:assert/strict');
const http=require('node:http');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.argv[2]||'playwright');
const root=path.join(__dirname,'dist');
const server=http.createServer((req,res)=>{
  const url=new URL(req.url,'http://localhost');
  const name=url.pathname==='/'?'index.html':url.pathname.slice(1);
  if(!['index.html','style.css','model.js','app.js','sample-quarterly-revenue.csv'].includes(name)){res.writeHead(404);res.end();return;}
  const types={'.html':'text/html','.css':'text/css','.js':'text/javascript','.csv':'text/csv'};
  res.setHeader('Content-Type',types[path.extname(name)]);res.end(fs.readFileSync(path.join(root,name)));
});
(async()=>{
  let browser;
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  try{
    browser=await chromium.launch({headless:true,...(process.argv[3]?{executablePath:process.argv[3]}:{})});
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    let requestCount=0;
    let mode='success';
    let requestContext;
    await page.route('https://generativelanguage.googleapis.com/**',async route=>{
      requestCount++;
      const req=route.request();
      assert.equal(req.url(),'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent');
      assert.equal(req.headers()['x-goog-api-key'],'browser-test-key');
      requestContext=JSON.parse(req.postDataJSON().contents[0].parts[0].text);
      if(mode==='quota'){await route.fulfill({status:429,contentType:'application/json',body:'{}'});return;}
      const bars=/bar/.test(requestContext.request);
      const layout={title:bars?'A new view':'Revenue outlook',reply:bars?'Changed to a bar chart, keeping the same verified forecast.':'Here is the monthly trend and forecast.',components:[{type:'metric',title:'Next month forecast',dataKey:'nextMonthForecast'},{type:bars?'barChart':'lineChart',title:'Actual and predicted revenue',dataKey:'revenueSeries'},{type:'table',title:'Monthly values',dataKey:'revenueSeries'}]};
      await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({responseId:'browser-test-response',candidates:[{finishReason:'STOP',content:{parts:[{text:JSON.stringify(layout)}]}}]})});
    });
    const origin=`http://127.0.0.1:${server.address().port}`;
    await page.goto(origin);
    assert.ok((await page.locator('#dashboard').innerText()).includes('A dashboard starts'));
    assert.equal(await page.locator('#export').isDisabled(),true);
    await page.locator('#load-sample').click();
    await page.locator('#file-list .file-row').waitFor();
    assert.equal(await page.locator('.data-table tbody tr').count(),3);
    await page.locator('#generate').click();
    assert.equal(requestCount,0);
    assert.ok((await page.locator('#status').innerText()).includes('API key'));
    await page.locator('#api-key').fill('browser-test-key');
    await page.locator('#generate').click();
    await page.locator('.actual-line').waitFor();
    assert.equal(requestCount,1);
    assert.ok((await page.locator('.metric-value').innerText()).includes('543,333.33'));
    assert.equal(await page.locator('.data-table tbody tr').count(),4);
    assert.ok((await page.locator('#provenance').innerText()).includes('browser-test-response'));
    const firstData=requestContext.data;
    await page.locator('#prompt').fill('Change this to a bar chart');
    await page.locator('#generate').click();
    await page.locator('.forecast-bar').waitFor();
    assert.equal(requestContext.conversation.length,2);
    assert.equal(requestContext.previousDashboard.title,'Revenue outlook');
    assert.deepEqual(requestContext.data,firstData);
    assert.equal(await page.locator('#chat-log .user').count(),2);
    await page.screenshot({path:'/tmp/sealed-revenue-desktop.png',fullPage:true});
    await page.locator('#schema-tab').click();
    const exported=JSON.parse(await page.locator('#schema').innerText());
    assert.equal(exported.layout.components[1].type,'barChart');
    assert.ok(!JSON.stringify(exported).includes('browser-test-key'));
    assert.deepEqual(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length})),{local:0,session:0});
    await page.locator('#preview-tab').click();
    mode='quota';
    await page.locator('#prompt').fill('Try another layout');
    await page.locator('#generate').click();
    await page.waitForFunction(()=>document.getElementById('status').textContent.includes('quota reached'));
    assert.equal(await page.locator('.forecast-bar').count(),1);
    assert.equal(await page.locator('#generate').isDisabled(),false);
    assert.ok((await page.locator('#chat-log .error').innerText()).includes('quota'));
    await page.locator('#file-input').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('month,revenue_usd\n2026-07,1\n2026-07,2\n2026-09,3')});
    await page.waitForFunction(()=>document.getElementById('status').textContent.includes('duplicate'));
    assert.equal(await page.locator('.forecast-bar').count(),0);
    assert.equal(await page.locator('#export').isDisabled(),true);
    mode='success';
    await page.locator('#file-input').setInputFiles({name:'different.csv',mimeType:'text/csv',buffer:Buffer.from('month,revenue_usd\n2026-10,100\n2026-11,200\n2026-12,300')});
    await page.locator('#file-list .file-row').waitFor();
    await page.locator('#prompt').fill('Predict next month with a line chart');
    await page.locator('#generate').click();
    await page.locator('.actual-line').waitFor();
    assert.equal(await page.locator('.metric-value').innerText(),'$400.00');
    assert.equal(requestContext.data.nextMonth,'2027-01');
    assert.equal(requestContext.conversation.length,0);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/sealed-revenue-mobile.png',fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile viewport must not overflow');
    await page.locator('#privacy-button').evaluate(el=>el.click());
    assert.equal(await page.locator('#privacy-dialog').isVisible(),true);
    await page.keyboard.press('Escape');
    await page.locator('#connection summary').click();
    await page.locator('#clear-key').click();
    assert.equal(await page.locator('#api-key').inputValue(),'');
    assert.deepEqual(errors,[]);
    console.log('Browser checks passed: CSV upload, real request wiring with intercepted responses, follow-up context, dynamic charts, errors, new data, key clearing, mobile layout. No live inference was called.');
  }finally{if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));}
})().catch(error=>{console.error(error);process.exitCode=1;});
