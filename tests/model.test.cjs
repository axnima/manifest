const assert=require('node:assert/strict');
const fs=require('node:fs');
const {readFile,parseCSV,analyze,validateComponent,generate,MAX_BYTES}=require('../public/model.js');
const file=(name,content)=>new File([content],name);
const sample=fs.readFileSync(__dirname+'/../public/sample-quarterly-revenue.csv','utf8');
const summary={title:'Team priorities',reply:'Here are the priorities from the memo.',source:'export default function App(){return <article style={{color:"pink"}}>Review collections.</article>}'};
assert.deepEqual(validateComponent(summary),summary);
assert.throws(()=>validateComponent({...summary,source:''}));
assert.throws(()=>validateComponent({...summary,source:'a'.repeat(200*1024+1)}));
assert.deepEqual(validateComponent({...summary,extra:'ignored'}),summary);
assert.equal(analyze(parseCSV(sample)).nextMonthForecast,543333.33);
(async()=>{
  const text=await readFile(file('memo.txt','Review collections.'));
  const arbitrary=await readFile(file('expenses.csv','category,cost\nPayroll,90000\nCloud,10000'));
  assert.ok(arbitrary.text.includes('Payroll'));assert.equal(text.text,'Review collections.');
  const pdf=await readFile(file('report.pdf',fs.readFileSync(__dirname+'/../samples/finance/quarterly-financial-report.pdf')),async(url)=>{
    assert.equal(url,'/api/extract?format=pdf');return {ok:true,json:async()=>({text:'Revenue 1240000'})};
  });
  assert.equal(pdf.mimeType,'text/plain');assert.equal(pdf.text,'Revenue 1240000');
  const image=await readFile(file('image.png',new Uint8Array([137,80,78,71,13,10,26,10,1])));assert.equal(image.mimeType,'image/png');assert.ok(image.base64);
  const office=await readFile(file('notes.docx','placeholder'),async(url,init)=>{assert.equal(url,'/api/extract?format=docx');assert.equal(init.method,'POST');return {ok:true,json:async()=>({text:'Extracted memo'})};});assert.equal(office.text,'Extracted memo');
  await assert.rejects(readFile(file('notes.docx','placeholder'),async()=>({status:501})),/Document extraction is unavailable/);
  await assert.rejects(readFile(file('bad.bin',new Uint8Array([0,1,2,255]))),/binary/);
  await assert.rejects(readFile(file('empty.txt','')),/non-empty/);
  await assert.rejects(readFile(file('big.txt','a'.repeat(MAX_BYTES+1))),/4 MB/);
  const args={documents:[text,pdf],prompt:'Summarize the collection priorities',history:[{role:'user',text:'Keep it brief'}],previous:summary};
  const result=await generate(args,async(url,init)=>{
    assert.equal(url,'/api/generate');assert.equal(init.headers.Authorization,undefined);
    const body=JSON.parse(init.body);
    assert.equal(body.documents[0].text,'Review collections.');
    assert.deepEqual(body.history,args.history);assert.deepEqual(body.previous,summary);assert.deepEqual(body.verifiedCalculations,[]);
    return {ok:true,json:async()=>({...summary,meta:{provider:'0G',sources:['memo.txt','report.pdf']},diagnostics:{stage:'complete'}})};
  });
  assert.equal(result.source,summary.source);assert.equal(result.meta.provider,'0G');
  await assert.rejects(generate({...args,documents:[]},()=>{}),/Attach/);
  await assert.rejects(generate(args,async()=>({ok:false,status:502,json:async()=>({error:'0G HTTP 429: usage limit reached'})})),/429/);
  await assert.rejects(generate(args,async()=>({ok:true,json:async()=>({...summary,source:''})})),/invalid React/);
  let diagnostic;
  await assert.rejects(generate({...args,onDiagnostics:d=>{diagnostic=d;}},async()=>({ok:false,status:502,json:async()=>({error:'MAX_TOKENS',diagnostics:{finishReason:'length',success:false}})})),/MAX_TOKENS/);
  assert.equal(diagnostic.finishReason,'length');assert.equal(diagnostic.success,false);
  await assert.rejects(generate({...args,onDiagnostics:()=>{throw Error('log');}},async()=>({ok:false,status:502,json:async()=>({error:'quota'})})),/quota/);
  console.log('Passed: files, local PDF/Office extraction, image transport, same-origin inference, response validation, forecast helper, errors. No live inference.');
})().catch(e=>{console.error(e);process.exitCode=1;});
