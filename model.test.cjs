const assert=require('node:assert/strict');
const fs=require('node:fs');
const {parseCSV,analyze,validateLayout,generate}=require('./dist/model.js');
const sample=fs.readFileSync(__dirname+'/dist/sample-quarterly-revenue.csv','utf8');
const rows=parseCSV(sample);
const analysis=analyze(rows);
assert.equal(analysis.totalRevenue,1240000);
assert.equal(analysis.nextMonthForecast,543333.33);
assert.equal(analysis.nextMonth,'2026-10');
assert.equal(analysis.monthlyGrowth,17.07);
assert.deepEqual(parseCSV('\ufeff"month","revenue_usd"\r\n"2026-09","480000"\r\n"2026-07","350000"\r\n"2026-08","410000"\r\n'),rows);
const csv=values=>'month,revenue_usd\n'+values.map((value,i)=>`2026-${String(i+10).padStart(2,'0')},${value}`).join('\n');
assert.equal(analyze(parseCSV(csv([10,10,10]))).nextMonth,'2027-01');
assert.equal(analyze(parseCSV(csv([10,10,10]))).nextMonthForecast,10);
assert.equal(analyze(parseCSV(csv([0,0,0]))).monthlyGrowth,null);
assert.equal(analyze(parseCSV(csv([30,10,0]))).nextMonthForecast,0);
assert.equal(analyze(parseCSV(csv([0.1,0.2,0.3]))).nextMonthForecast,0.4);
for(const invalid of ['',sample.replace('month','date'),sample.replace('2026-08','2026-07'),sample.replace('2026-08','2026-11'),sample.replace('2026-08','2026-13'),sample.replace('410000','NaN'),sample.replace('410000','-1'),sample.replace('410000','1000000001'),sample.replace('410000','12.345'),sample.replace('410000','=HYPERLINK("bad")'),sample.replace('2026-08,410000\n',''),'x'.repeat(102401)])assert.throws(()=>parseCSV(invalid));
const layout={title:'Next month',reply:'I put the forecast first.',components:[{type:'metric',title:'Forecast',dataKey:'nextMonthForecast'},{type:'lineChart',title:'Revenue trend',dataKey:'revenueSeries'}]};
assert.deepEqual(validateLayout(layout),layout);
assert.throws(()=>validateLayout({...layout,components:[{type:'script',title:'Bad',dataKey:'revenueSeries'}]}));
assert.throws(()=>validateLayout({...layout,components:[{type:'metric',title:'Bad binding',dataKey:'revenueSeries'}]}));
assert.throws(()=>validateLayout({...layout,components:[]}));
assert.throws(()=>validateLayout({...layout,components:[layout.components[0]]}));
assert.throws(()=>validateLayout({...layout,components:[{type:'__proto__',title:'Bad',dataKey:'revenueSeries'}]}));
assert.deepEqual(validateLayout({...layout,html:'<script>bad</script>'}),layout);
const args={apiKey:'test-key-not-a-secret',rows,prompt:'Forecast next month',history:[{role:'user',text:'Use bars'}],previous:layout};
(async()=>{
  let calls=0;
  const result=await generate(args,async(url,init)=>{
    calls++;assert.equal(url,'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent');
    assert.equal(init.headers['x-goog-api-key'],'test-key-not-a-secret');
    const body=JSON.parse(init.body),context=JSON.parse(body.contents[0].parts[0].text);
    assert.equal(context.data.nextMonthForecast,543333.33);
    assert.deepEqual(context.previousDashboard,layout);assert.deepEqual(context.conversation,args.history);
    assert.ok(!init.body.includes('test-key-not-a-secret'));
    return {ok:true,json:async()=>({responseId:'provider-test-id',candidates:[{finishReason:'STOP',content:{parts:[{text:JSON.stringify(layout)}]}}]})};
  });
  assert.equal(calls,1);assert.deepEqual(result.layout,layout);assert.equal(result.meta.responseId,'provider-test-id');
  assert.ok(!JSON.stringify(result).includes('test-key-not-a-secret'));
  await assert.rejects(generate({...args,apiKey:''},()=>{throw new Error('must not call');}),/API key/);
  await assert.rejects(generate(args,async()=>({ok:false,status:404})),/gemini-3\.5-flash-lite \(HTTP 404\)/);
  await assert.rejects(generate(args,async()=>({ok:false,status:429})),/quota/);
  await assert.rejects(generate(args,async()=>({ok:false,status:403})),/access denied/);
  await assert.rejects(generate(args,async()=>{throw new TypeError('network');}),/reach Gemini/);
  await assert.rejects(generate(args,async()=>({ok:true,json:async()=>({candidates:[{finishReason:'MAX_TOKENS'}]})})),/did not complete/);
  await assert.rejects(generate(args,async()=>({ok:true,json:async()=>({candidates:[{finishReason:'STOP',content:{parts:[{text:'not JSON'}]}}]})})),/valid component JSON/);
  console.log('Passed: CSV validation, forecast arithmetic, calendar rollover, layout validation, request context, key exclusion, and provider failures. Provider responses are test doubles, not live calls.');
})().catch(error=>{console.error(error);process.exitCode=1;});
